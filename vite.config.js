/* ============================================================
 * Vite 配置文件
 * ============================================================
 * 【Vite 是什么】
 * 它是一个「开发服务器 + 打包工具」：
 *   开发时（npm run dev） → 起一个本地服务器，改代码后浏览器自动刷新
 *   上线时（npm run build）→ 把 src 里的一堆模块合并压缩成 dist 目录
 *
 * 这个文件告诉 Vite「怎么干活」。不用 defineConfig 也能写，
 * 但用它包一层，编辑器就能给出参数提示，写错了会标红。
 * ============================================================ */

import { defineConfig } from "vite";

export default defineConfig({
  /* base 决定打包后资源（js/css）的引用路径前缀。
     "./" 表示用「相对路径」引用，好处是：
       把 dist 目录直接扔到 GitHub Pages 的子路径
       （https://你的名字.github.io/myapp/）下也能正常打开。
     如果保持默认值 "/"，浏览器会去 https://你的名字.github.io/src/xxx.js
     找文件，正好少了一层 myapp，结果 404 白屏。 */
  base: "./",

  server: {
    // 开发服务器端口。被占用时 Vite 会自动换成 5174、5175……
    port: 5173,
    // 不自动打开浏览器（免得每次启动都弹窗）
    open: false,
  },

  build: {
    // 打包产物放到 dist 目录（默认就是它，写出来更明确）
    outDir: "dist",
    // 生成 sourcemap：打包后的代码被压缩得没法看，
    // 有了它浏览器报错时仍能定位到 src 里的原始行号，方便调试
    sourcemap: true,
  },
});
